#!/usr/bin/env bash
# Start a long job detached, so it survives the session that started it.
# A training run that dies with the agent is the most expensive kind of lost work.
set -euo pipefail

usage() {
  cat <<'USAGE'
usage: launch.sh <exp> [--force] -- <cmd...>

Run <cmd...> from the lab root, detached, logging to experiments/<exp>/train.log.
Writes run.pid, sets status=running, and on exit records exit_code and sets
status to done (0) or dead (nonzero). Harvest with bin/collect.sh.

  <exp>     experiment id or numeric prefix
  --force   launch even though the plan is not pre-registered

Example: launch.sh 003 -- python -m lib.train --arm treatment --seed 0
USAGE
}

FORCE=0
IDENT=""
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --force) FORCE=1; shift ;;
    --) shift; break ;;
    -*) echo "error: unknown option $1" >&2; exit 1 ;;
    *) IDENT="$1"; shift ;;
  esac
done
[ -n "$IDENT" ] || { usage >&2; exit 1; }
[ $# -gt 0 ] || { echo "error: no command after --" >&2; usage >&2; exit 1; }

find_lab_root() {
  local d; d="$(pwd -P)"
  while [ "$d" != "/" ]; do
    if [ -f "$d/lab.json" ]; then echo "$d"; return 0; fi
    d="$(dirname "$d")"
  done
  return 1
}
ROOT="$(find_lab_root)" || { echo "error: not inside a research lab (no lab.json here or above)" >&2; exit 1; }

resolve_exp() {
  local root="$1" ident="$2" d base n=0 hit=""
  if [ -d "$root/experiments/$ident" ]; then echo "$ident"; return 0; fi
  case "$ident" in
    ''|*[!0-9]*) ;;
    *) ident="$(printf '%03d' "$((10#$ident))")" ;;
  esac
  for d in "$root"/experiments/"$ident"-*/; do
    [ -d "$d" ] || continue
    base="$(basename "$d")"; hit="$base"; n=$((n + 1))
  done
  [ "$n" -eq 1 ] || return 1
  echo "$hit"
}
EXP="$(resolve_exp "$ROOT" "$IDENT")" || { echo "error: no single experiment matching '$IDENT'" >&2; exit 1; }
DIR="$ROOT/experiments/$EXP"

if [ ! -f "$DIR/.prereg" ] && [ "$FORCE" -ne 1 ]; then
  echo "error: $EXP is not pre-registered — run bin/prereg.sh $EXP first." >&2
  echo "       Kill criteria and predictions are fixed before the compute is spent, not after." >&2
  echo "       Use --force for a job that is not an experiment run (a smoke test, a profile)." >&2
  exit 1
fi

# A previous result must not be mistaken for this one's.
rm -f "$DIR/exit_code" "$DIR/.collected"

# No 'set -e' in the wrapper: it must reach the exit-code capture even on failure.
CMDQ="$(printf '%q ' "$@")"
cat > "$DIR/.run.sh" <<RUNEOF
#!/usr/bin/env bash
# Generated by launch.sh; regenerated on every launch. Do not edit.
cd $(printf '%q' "$ROOT") || exit 127
$CMDQ
rc=\$?
echo "\$rc" > $(printf '%q' "$DIR/exit_code")
if [ "\$rc" -eq 0 ]; then
  echo done > $(printf '%q' "$DIR/status")
else
  echo dead > $(printf '%q' "$DIR/status")
fi
RUNEOF
chmod +x "$DIR/.run.sh"

{
  echo "=== launch $(date -u +%Y-%m-%dT%H:%M:%SZ): $*"
} >> "$DIR/train.log"

# setsid where it exists (Linux); macOS has nohup + disown only.
if command -v setsid >/dev/null 2>&1; then
  nohup setsid bash "$DIR/.run.sh" >> "$DIR/train.log" 2>&1 &
else
  nohup bash "$DIR/.run.sh" >> "$DIR/train.log" 2>&1 &
fi
PID=$!
disown "$PID" 2>/dev/null || true

echo "$PID" > "$DIR/run.pid"
echo "running" > "$DIR/status"

echo "launched $EXP  pid=$PID"
echo "log: $DIR/train.log"
echo "collect with bin/collect.sh"
